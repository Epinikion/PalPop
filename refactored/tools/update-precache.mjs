import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
async function walk(folder) {
  const entries = await fs.readdir(path.join(root, folder), { withFileTypes: true });
  return (
    await Promise.all(
      entries.map((entry) =>
        entry.isDirectory() ? walk(folder + '/' + entry.name) : [folder + '/' + entry.name],
      ),
    )
  ).flat();
}
const assets = [
  './',
  'index.html',
  'manifest.webmanifest',
  'icon-192.png',
  'icon-512.png',
  'apple-touch-icon.png',
  'tools/pal-designer.html',
  ...(await walk('src')),
  ...(await walk('styles')),
  ...(await walk('assets')),
].sort();
const hash = createHash('sha256');
for (const asset of assets) {
  hash.update(asset);
  hash.update(await fs.readFile(path.join(root, asset === './' ? 'index.html' : asset)));
}
hash.update(await fs.readFile(path.join(root, 'sw.js')));
const output = `// Generated by npm run cache:update.\nconst CACHE_VERSION=${JSON.stringify(hash.digest('hex').slice(0, 16))};\nconst PRECACHE=${JSON.stringify(assets, null, 2)};\n`;
const destination = path.join(root, 'precache.js');
if (process.argv.includes('--check')) {
  if ((await fs.readFile(destination, 'utf8')) !== output)
    throw new Error('Precache is stale. Run npm run cache:update.');
  console.log('Offline cache matches all app assets.');
} else {
  await fs.writeFile(destination, output);
  console.log(`Prepared ${assets.length} offline assets.`);
}
